import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { compilePreferences } from './compileCharacterSecondaryPreferences.mjs';
import { createFrontendLoader } from './lib/loadFrontend.mjs';
const load = createFrontendLoader();
const groupRolls = load('src/utils/characterSecondaryRolls.js').default;
assert.equal(groupRolls({ secondaryStats: [{type:'Offense',rolls:2},{type:'Offense %',rolls:3}] }).offense, 5);
const worker = vm.createContext({self:{},postMessage(){}});
vm.runInContext(fs.readFileSync('public/workers/optimizer.js','utf8'),worker);
const weights = {health:1,speed:0};
assert.equal(worker.characterGGValue(50,{health:5},weights),60.00000000000001);
assert.equal(worker.characterGGValue(50,{speed:5},weights),40);
assert.equal(worker.characterGGValue(50,{health:2,speed:2},weights),50);
assert.equal(worker.characterGGValue(50,{health:2},null),50);
assert.equal(worker.characterGGValue(null,{health:2},weights),null);
assert.ok(worker.characterGGValue(51,{health:1,speed:4},weights) < worker.characterGGValue(50,{health:4,speed:1},weights));
assert.ok(worker.characterGGValue(30,{health:5},weights) < worker.characterGGValue(60,{speed:5},weights));
const slots=['square','arrow','diamond','triangle','circle','cross'];
const mods=slots.flatMap(slot=>['preferred','plain'].map(kind=>({id:slot+kind,slot,set:{name:'health'},pips:5,primaryStat:{type:'Health %'}})));
const scores=Object.fromEntries(mods.map(mod=>[mod.id,mod.id.endsWith('preferred')?50:51]));
const rolls=Object.fromEntries(mods.map(mod=>[mod.id,mod.id.endsWith('preferred')?{health:4,speed:1}:{health:1,speed:4}]));
const gg={characterWeighted:true,scores,rolls,preferences:{A:{weights}},restrictions:{A:{primaries:{},setCombinations:[{health:3}]}}};
const characters={A:{baseID:'A',playerValues:{gearLevel:13},optimizerSettings:{minimumModDots:5}}};
const order=[{id:'A',target:{}}];
const result=worker.optimizeGGMods(mods,characters,order,{},gg)[0];
assert.ok(result.assignedMods.every(id=>id.endsWith('preferred')));
assert.match(result.messages[0],/50.0 \(unadjusted\)/);
assert.ok(worker.optimizeGGMods(mods,characters,order,{}, {...gg,characterWeighted:false})[0].assignedMods.every(id=>id.endsWith('plain')));
assert.ok(worker.optimizeGGMods(mods,characters,order,{}, {...gg,preferences:{}})[0].assignedMods.every(id=>id.endsWith('plain')));
const stats={1:{count:100,frequency:0.2,average:100},55:{count:100,frequency:0.2,average:0.02},5:{count:100,frequency:0.2,average:10}};
const raw={characters:{A:{population:{sampleSize:100},aggregate:{secondaries:{stats}},loadouts:{top:{id:'top',count:100,setIds:[1,1,1],secondaries:{observedCount:300,stats}}}}}};
const target={characters:{A:{targets:[{metaRestrictions:{setCombinations:[{health:3}]}}]}}};
const generated=compilePreferences(raw,target);
assert.equal(generated.characters.A.weights.health,generated.characters.A.weights.speed,'Two forms do not double the preference');
assert.equal(generated.characters.A.loadoutId,'top');
raw.characters.A.loadouts.top.count=1;
assert.ok(compilePreferences(raw,target).characters.A.weights.health < 0.51,'Small samples approach neutral');
const saved=JSON.parse(fs.readFileSync('src/constants/generatedCharacterSecondaryPreferences.json'));
assert.equal(Object.keys(saved.characters).length,340);
for(const c of Object.values(saved.characters)) for(const value of Object.values(c.weights)) assert.ok(value>=0&&value<=1);
assert.equal(saved.schemaVersion,2);
assert.ok(saved.characters.WAMPA.weights.tenacity > saved.characters.WAMPA.weights.speed);
assert.ok(saved.characters.CHEWBACCALEGENDARY.weights.tenacity > saved.characters.CHEWBACCALEGENDARY.weights.speed);
assert.ok(Object.values(saved.characters).filter(c=>c.weights.speed===Math.max(...Object.values(c.weights))).length<100,
  'Population normalization must not simply repeat universal Speed popularity');
console.log('Passed character-weighted GG: grouped rolls, bounds, quality tradeoff, actual selection, unchanged GG, fallback, generation and sample confidence.');
